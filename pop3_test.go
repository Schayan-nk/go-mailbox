// A fake POP3 server, so the client is tested against the protocol rather
// than against a description of it.
//
// THE PART MOST LIKELY TO BE WRONG is dot-stuffing. A multi-line response
// ends at a line containing exactly ".", and any body line that begins with a
// "." is sent with an extra one so that real content cannot imitate the
// terminator. A reader that ignores that either stops early -- losing the
// rest of the message with no error -- or leaves a spurious dot at the start
// of a line. Both are silent, and neither shows up on the short ASCII
// messages a test usually invents. So the message below contains a line that
// is a single dot, and a line that begins with one.

type fakePOP3 struct {
	ln    net.Listener
	msgs  []string // in mailbox order
	uids  []string
	pool  *x509.CertPool
	creds [2]string

	mu  sync.Mutex
	saw []string
	wg  sync.WaitGroup
	// deleted records DELE, so a test can prove nothing ever sends one.
	deleted []int
}

func newFakePOP3(t *testing.T, msgs []string, uids []string) *fakePOP3 {
	t.Helper()
	cert, pool := selfSignedPOP(t)
	ln, err := tls.Listen("tcp", "127.0.0.1:0", &tls.Config{
		Certificates: []tls.Certificate{cert},
		MinVersion:   tls.VersionTLS12,
	})
	if err != nil {
		t.Fatalf("listen: %v", err)
	}
	f := &fakePOP3{
		ln: ln, msgs: msgs, uids: uids, pool: pool,
		creds: [2]string{"owner@example.com", "p@ss word"},
	}
	f.wg.Add(1)
	go f.serve()
	t.Cleanup(func() { ln.Close(); f.wg.Wait() })
	return f
}

func (f *fakePOP3) port() int { return f.ln.Addr().(*net.TCPAddr).Port }

func (f *fakePOP3) commands() []string {
	f.mu.Lock()
	defer f.mu.Unlock()
	return append([]string(nil), f.saw...)
}

func (f *fakePOP3) serve() {
	defer f.wg.Done()
	for {
		c, err := f.ln.Accept()
		if err != nil {
			return
		}
		go f.session(c)
	}
}

// stuff applies dot-stuffing, the way a real server must.
func stuff(body string) string {
	var b strings.Builder
	for _, line := range strings.Split(body, "\r\n") {
		if strings.HasPrefix(line, ".") {
			b.WriteByte('.')
		}
		b.WriteString(line)
		b.WriteString("\r\n")
	}
	return b.String()
}

func (f *fakePOP3) session(c net.Conn) {
	defer c.Close()
	r := bufio.NewReader(c)
	w := bufio.NewWriter(c)
	defer w.Flush()

	fmt.Fprint(w, "+OK fake POP3 ready\r\n")
	w.Flush()

	for {
		line, err := r.ReadString('\n')
		if err != nil {
			return
		}
		line = strings.TrimRight(line, "\r\n")
		f.mu.Lock()
		f.saw = append(f.saw, line)
		f.mu.Unlock()

		verb, rest, _ := strings.Cut(line, " ")
		switch strings.ToUpper(verb) {
		case "USER", "PASS":
			fmt.Fprint(w, "+OK\r\n")
		case "STAT":
			fmt.Fprintf(w, "+OK %d 1024\r\n", len(f.msgs))
		case "UIDL":
			fmt.Fprint(w, "+OK\r\n")
			for i, u := range f.uids {
				fmt.Fprintf(w, "%d %s\r\n", i+1, u)
			}
			fmt.Fprint(w, ".\r\n")
		case "LIST":
			fmt.Fprint(w, "+OK\r\n")
			for i, m := range f.msgs {
				fmt.Fprintf(w, "%d %d\r\n", i+1, len(m))
			}
			fmt.Fprint(w, ".\r\n")
		case "TOP":
			num, linesArg, _ := strings.Cut(rest, " ")
			n, _ := strconv.Atoi(num)
			want, _ := strconv.Atoi(linesArg)
			if n < 1 || n > len(f.msgs) {
				fmt.Fprint(w, "-ERR no such message\r\n")
				break
			}
			raw := f.msgs[n-1]
			head, body, _ := strings.Cut(raw, "\r\n\r\n")
			kept := strings.Split(body, "\r\n")
			if len(kept) > want {
				kept = kept[:want]
			}
			fmt.Fprint(w, "+OK\r\n")
			fmt.Fprint(w, stuff(head+"\r\n\r\n"+strings.Join(kept, "\r\n")))
			fmt.Fprint(w, ".\r\n")
		case "RETR":
			n, _ := strconv.Atoi(strings.TrimSpace(rest))
			if n < 1 || n > len(f.msgs) {
				fmt.Fprint(w, "-ERR no such message\r\n")
				break
			}
			fmt.Fprint(w, "+OK\r\n")
			fmt.Fprint(w, stuff(f.msgs[n-1]))
			fmt.Fprint(w, ".\r\n")
		case "DELE":
			n, _ := strconv.Atoi(strings.TrimSpace(rest))
			f.mu.Lock()
			f.deleted = append(f.deleted, n)
			f.mu.Unlock()
			fmt.Fprint(w, "+OK\r\n")
		case "QUIT":
			fmt.Fprint(w, "+OK bye\r\n")
			w.Flush()
			return
		default:
			fmt.Fprint(w, "-ERR unknown\r\n")
		}
		w.Flush()
	}
}

// trustThisPOP lets the client verify the test server's certificate.
//
// NOT InsecureSkipVerify. The certificate is generated by this test, so the
// test hands the client a root pool holding exactly that one -- verification
// stays ON and is merely told what to trust. Turning it off would test a
// client that is not the client being shipped, and would leave the pattern in
// the file for somebody to copy somewhere it matters.
func trustThisPOP(t *testing.T, f *fakePOP3) func() {
	t.Helper()
	prev := tlsConfigFor
	tlsConfigFor = func(host string) *tls.Config {
		return &tls.Config{ServerName: host, RootCAs: f.pool, MinVersion: tls.VersionTLS12}
	}
	return func() { tlsConfigFor = prev }
}

func selfSignedPOP(t *testing.T) (tls.Certificate, *x509.CertPool) {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("key: %v", err)
	}
	tmpl := x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "127.0.0.1"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(time.Hour),
		IPAddresses:           []net.IP{net.ParseIP("127.0.0.1")},
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageCertSign,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	der, err := x509.CreateCertificate(rand.Reader, &tmpl, &tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatalf("cert: %v", err)
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	pool := x509.NewCertPool()
	pool.AddCert(leaf)
	return tls.Certificate{Certificate: [][]byte{der}, PrivateKey: key}, pool
}

func popConfig(f *fakePOP3) Config {
	return Config{
		Address: f.creds[0], Password: f.creds[1],
		POP3Host: "127.0.0.1", POP3Port: f.port(),
	}
}

// THE TRAP MESSAGE. Its body holds a line that is a single dot and a line
// that starts with one -- the two shapes dot-stuffing exists for.
func dottedMessage() string {
	return "From: \"Karimi, Nima\" <n.karimi@example.com>\r\n" +
		"Subject: =?UTF-8?B?" + base64.StdEncoding.EncodeToString([]byte("پیش‌فاکتور")) + "?=\r\n" +
		"Content-Type: text/plain; charset=utf-8\r\n" +
		"\r\n" +
		"first line\r\n" +
		".\r\n" +
		".hidden leading dot\r\n" +
		"last line"
}

func plainPOPMessage(subject string) string {
	return "From: a@b.com\r\nSubject: " + subject + "\r\n" +
		"Content-Type: text/plain; charset=utf-8\r\n\r\nhello there"
}

// The whole path: connect, sign in, list ids and sizes, preview, read.
func TestPOP3ReadsAMailbox(t *testing.T) {
	f := newFakePOP3(t,
		[]string{plainPOPMessage("first"), dottedMessage(), plainPOPMessage("third")},
		[]string{"uid-one", "uid-two", "uid-three"})
	restore := trustThisPOP(t, f)
	defer restore()

	box, err := OpenPOP3(popConfig(f))
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	defer box.Close()

	uids := box.UIDs()
	if len(uids) != 3 || uids[1] != "uid-two" {
		t.Fatalf("UIDs are %v", uids)
	}
	if box.Count() != 3 {
		t.Errorf("Count is %d, want 3", box.Count())
	}

	sizes, err := box.Sizes()
	if err != nil {
		t.Fatalf("sizes: %v", err)
	}
	if sizes["uid-two"] != int64(len(dottedMessage())) {
		t.Errorf("size of uid-two is %d, want %d", sizes["uid-two"], len(dottedMessage()))
	}

	// THE TRAP, through TOP. Every line must survive, the lone dot must not
	// end the response early, and the stuffed dot must come back as one dot.
	p, err := box.Preview("uid-two")
	if err != nil {
		t.Fatalf("preview: %v", err)
	}
	if p.UIDL != "uid-two" {
		t.Errorf("preview UIDL is %q", p.UIDL)
	}
	if p.Subject != "پیش‌فاکتور" {
		t.Errorf("subject is %q, want the Persian", p.Subject)
	}
	if p.Addr != "n.karimi@example.com" {
		t.Errorf("address is %q", p.Addr)
	}
	for _, want := range []string{"first line", ".hidden leading dot", "last line"} {
		if !strings.Contains(p.Body, want) {
			t.Errorf("the preview lost %q; it is:\n%s", want, p.Body)
		}
	}
	if strings.Contains(p.Body, "..hidden") {
		t.Errorf("the stuffed dot was not removed; the body is:\n%s", p.Body)
	}

	// And through RETR, which is a different code path to the same bytes.
	full, err := box.Message("uid-two")
	if err != nil {
		t.Fatalf("message: %v", err)
	}
	for _, want := range []string{"first line", ".hidden leading dot", "last line"} {
		if !strings.Contains(full.Body, want) {
			t.Errorf("the full fetch lost %q; it is:\n%s", want, full.Body)
		}
	}
	if full.Subject != p.Subject {
		t.Errorf("RETR and TOP disagree about the subject: %q vs %q", full.Subject, p.Subject)
	}
}

// READING NEVER SENDS DELE.
//
// POP3's only removal destroys the message when the session ends, and there
// is no trash folder to move it to instead. This is the test that says
// listing, previewing and opening have no path to the destructive command,
// however they are driven. Delete is the one that does
// (TestOnlyDeleteRemovesAndOnlyQUITCommitsIt).
func TestNothingEverDeletesFromTheServer(t *testing.T) {
	f := newFakePOP3(t, []string{plainPOPMessage("x")}, []string{"uid-one"})
	restore := trustThisPOP(t, f)
	defer restore()

	box, err := OpenPOP3(popConfig(f))
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	if _, err := box.Preview("uid-one"); err != nil {
		t.Fatalf("preview: %v", err)
	}
	if _, err := box.Message("uid-one"); err != nil {
		t.Fatalf("message: %v", err)
	}
	if _, err := box.Sizes(); err != nil {
		t.Fatalf("sizes: %v", err)
	}
	box.Close()

	for _, c := range f.commands() {
		if strings.HasPrefix(strings.ToUpper(c), "DELE") {
			t.Errorf("the client sent %q", c)
		}
	}
	f.mu.Lock()
	n := len(f.deleted)
	f.mu.Unlock()
	if n != 0 {
		t.Errorf("%d messages were deleted on the server", n)
	}
}

// Raw is the message byte for byte; Delete sends DELE for that message alone;
// Commit ends the session with QUIT and says the server took it.
func TestOnlyDeleteRemovesAndOnlyQUITCommitsIt(t *testing.T) {
	f := newFakePOP3(t, []string{plainPOPMessage("one"), plainPOPMessage("two")}, []string{"uid-one", "uid-two"})
	restore := trustThisPOP(t, f)
	defer restore()

	box, err := OpenPOP3(popConfig(f))
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	raw, err := box.Raw("uid-two")
	if err != nil || !strings.Contains(string(raw), "Subject: two") {
		t.Fatalf("raw: %q, %v", raw, err)
	}
	if err := box.Delete("uid-two"); err != nil {
		t.Fatalf("delete: %v", err)
	}
	if err := box.Delete("uid-none"); err == nil {
		t.Error("a message not in the mailbox was deleted")
	}
	if err := box.Commit(); err != nil {
		t.Fatalf("commit: %v", err)
	}
	f.mu.Lock()
	deleted := append([]int(nil), f.deleted...)
	f.mu.Unlock()
	if len(deleted) != 1 || deleted[0] != 2 {
		t.Errorf("deleted %v, want [2]", deleted)
	}
	cmds := f.commands()
	if len(cmds) == 0 || strings.ToUpper(cmds[len(cmds)-1]) != "QUIT" {
		t.Errorf("the session did not end with QUIT: %v", cmds)
	}
}

// The session is closed with QUIT, not dropped.
//
// POP3 holds an EXCLUSIVE LOCK on the mailbox for the length of a session.
// An abandoned one keeps everybody else out -- including the same person's
// desktop client -- until the server's own timeout expires.
func TestTheSessionIsClosedPolitely(t *testing.T) {
	f := newFakePOP3(t, []string{plainPOPMessage("x")}, []string{"uid-one"})
	restore := trustThisPOP(t, f)
	defer restore()

	box, err := OpenPOP3(popConfig(f))
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	box.Close()

	var sawQuit bool
	for _, c := range f.commands() {
		if strings.EqualFold(strings.TrimSpace(c), "QUIT") {
			sawQuit = true
		}
	}
	if !sawQuit {
		t.Errorf("the session ended without QUIT; commands were %v", f.commands())
	}
}

// A password with a line break in it is refused rather than sent.
//
// POP3 has no quoting: PASS takes the rest of the line. A password containing
// a newline would therefore be sent as two commands, and the second would be
// whatever came after the break -- so this is caught here rather than left
// for the server to make sense of.
func TestAPasswordWithALineBreakIsRefused(t *testing.T) {
	f := newFakePOP3(t, []string{plainPOPMessage("x")}, []string{"uid-one"})
	restore := trustThisPOP(t, f)
	defer restore()

	cfg := popConfig(f)
	cfg.Password = "good\r\nSTAT"
	if _, err := OpenPOP3(cfg); err == nil {
		t.Fatal("a password containing a line break was accepted")
	}
	for _, c := range f.commands() {
		if strings.EqualFold(strings.TrimSpace(c), "STAT") {
			t.Errorf("the injected command reached the server: %q", c)
		}
	}
}

// An empty mailbox is an answer, not an error.
func TestAnEmptyPOP3MailboxIsNotAnError(t *testing.T) {
	f := newFakePOP3(t, nil, nil)
	restore := trustThisPOP(t, f)
	defer restore()

	box, err := OpenPOP3(popConfig(f))
	if err != nil {
		t.Fatalf("open: %v", err)
	}
	defer box.Close()
	if n := box.Count(); n != 0 {
		t.Errorf("Count is %d on an empty mailbox", n)
	}
	if uids := box.UIDs(); len(uids) != 0 {
		t.Errorf("UIDs are %v on an empty mailbox", uids)
	}
}

// An unconfigured mailbox is refused before any connection is attempted.
func TestOpenPOP3RefusesAnUnconfiguredMailbox(t *testing.T) {
	if _, err := OpenPOP3(Config{}); err == nil {
		t.Fatal("an empty configuration opened a mailbox")
	}
	if _, err := OpenPOP3(Config{Address: "a@b.com", POP3Host: "h"}); err == nil {
		t.Fatal("a configuration with no password opened a mailbox")
	}
}
